import React, { useEffect, useId, useState } from "react";
import { ImageIcon, Pencil, Plus, X } from "lucide-react";
import FormDialog from "../../../shared/ui/FormDialog";
import TextField from "../../../shared/ui/TextField";
import SelectField from "../../../shared/ui/SelectField";
import Button from "../../../shared/ui/Button";
import MediaPickerModal from "../../media-library/components/MediaPickerModal";
import { getAssetUrl } from "../../../shared/utils/assetUrl";
import { DEPARTMENT_OPTIONS, clientInitials } from "../format";

const EMPTY = {
  companyName: "",
  slug: "",
  contactName: "",
  primaryEmail: "",
  phone: "",
  industry: "",
  country: "",
  code: "",
  notes: "",
  isActive: true,
  department: "digital_agency",
  logoUrl: "",
  logoMediaId: "",
};

// Client account form (PUI-3). Same fields and API payload as before. In edit
// mode, clearing an optional field now clears it (empty values used to be
// dropped). The slug stays optional: left empty it is generated by the API.
export default function CustomerFormModal({ open, mode = "create", initial = null, onClose, onSubmit, busy }) {
  const isEdit = mode === "edit";
  const [f, setF] = useState(EMPTY);
  const deptLabelId = useId();
  const [logoPickerOpen, setLogoPickerOpen] = useState(false);

  useEffect(() => {
    if (!open) return;
    const c = initial || {};
    setF({
      companyName: c.companyName || "",
      slug: c.slug || "",
      contactName: c.contactName || "",
      primaryEmail: c.primaryEmail || "",
      phone: c.phone || "",
      industry: c.industry || "",
      country: c.country || "",
      code: c.code || "",
      notes: c.notes || "",
      isActive: typeof c.isActive === "boolean" ? c.isActive : true,
      department: c.department || "digital_agency",
      logoUrl: c.logoUrl || "",
      logoMediaId: c.logoMediaId || "",
    });
  }, [open, initial]);

  const set = (k) => (e) => setF((s) => ({ ...s, [k]: e?.target ? e.target.value : e }));
  const canSubmit = Boolean(f.companyName.trim() && f.contactName.trim());

  const payload = () => {
    const opt = (v) => (isEdit ? v.trim() : v.trim() || undefined);
    return {
      companyName: f.companyName.trim(),
      slug: f.slug.trim() || undefined,
      contactName: f.contactName.trim(),
      primaryEmail: opt(f.primaryEmail),
      phone: opt(f.phone),
      industry: opt(f.industry),
      country: opt(f.country),
      code: opt(f.code),
      notes: opt(f.notes),
      isActive: Boolean(f.isActive),
      department: f.department,
      logoUrl: isEdit ? f.logoUrl || "" : f.logoUrl || undefined,
      logoMediaId: isEdit ? f.logoMediaId || null : f.logoMediaId || undefined,
    };
  };

  return (
    <>
      <FormDialog
        open={open}
        title={isEdit ? "Edit client" : "New client"}
        description={isEdit ? "Update the client's details." : "Add a client account. Projects, services and portal users are linked to it."}
        onClose={onClose}
        onSubmit={() => onSubmit?.(payload())}
        busy={busy}
        canSubmit={canSubmit}
        submitLabel={isEdit ? "Save changes" : "Create client"}
        submitIcon={isEdit ? Pencil : Plus}
      >
        <fieldset className="px-form-section">
          <legend>Company</legend>
          <div className="px-form-grid px-form-grid--2">
            <TextField label="Company name" required value={f.companyName} onChange={set("companyName")} />
            <TextField label="Client code" value={f.code} onChange={set("code")} hint="For example EXP-001." />
          </div>
          <div className="px-field">
            <span className="px-label" id={deptLabelId}>
              Department
            </span>
            {/* ARIA radio group: one Tab stop; arrow keys move and select. */}
            <div className="px-choice-row" role="radiogroup" aria-labelledby={deptLabelId}>
              {DEPARTMENT_OPTIONS.map((o, i) => {
                const checked = f.department === o.value;
                const focusable = checked || (!DEPARTMENT_OPTIONS.some((x) => x.value === f.department) && i === 0);
                return (
                  <button
                    key={o.value}
                    type="button"
                    role="radio"
                    aria-checked={checked}
                    tabIndex={focusable ? 0 : -1}
                    className="px-choice"
                    title={o.hint}
                    onClick={() => setF((st) => ({ ...st, department: o.value }))}
                    onKeyDown={(e) => {
                      const step = { ArrowRight: 1, ArrowDown: 1, ArrowLeft: -1, ArrowUp: -1 }[e.key];
                      if (!step) return;
                      e.preventDefault();
                      const next = DEPARTMENT_OPTIONS[(i + step + DEPARTMENT_OPTIONS.length) % DEPARTMENT_OPTIONS.length];
                      setF((st) => ({ ...st, department: next.value }));
                      const buttons = e.currentTarget.parentElement.querySelectorAll('[role="radio"]');
                      buttons[(i + step + buttons.length) % buttons.length]?.focus();
                    }}
                  >
                    {o.label}
                  </button>
                );
              })}
            </div>
            <span className="px-hint">Decides which areas (projects and services, or procurement) the client page shows.</span>
          </div>
          <div className="px-form-grid px-form-grid--2">
            <SelectField
              label="Status"
              value={f.isActive ? "true" : "false"}
              onChange={(v) => setF((s) => ({ ...s, isActive: v === "true" }))}
              options={[
                { value: "true", label: "Active" },
                { value: "false", label: "Inactive" },
              ]}
            />
            <TextField label="Web address name (slug)" value={f.slug} onChange={set("slug")} hint="Generated from the company name if left empty." />
          </div>
          <div className="px-field">
            <span className="px-label">Logo</span>
            <div style={{ display: "flex", alignItems: "center", gap: 12 }}>
              <span className="px-logo px-logo--lg" aria-hidden="true">
                {f.logoUrl ? <img src={getAssetUrl(f.logoUrl)} alt="" /> : clientInitials(f.companyName)}
              </span>
              <Button size="sm" variant="outline" onClick={() => setLogoPickerOpen(true)}>
                <ImageIcon size={14} aria-hidden="true" />
                {f.logoUrl ? "Change logo" : "Choose logo"}
              </Button>
              {f.logoUrl ? (
                <Button size="sm" variant="ghost" onClick={() => setF((s) => ({ ...s, logoUrl: "", logoMediaId: "" }))}>
                  <X size={14} aria-hidden="true" />
                  Remove
                </Button>
              ) : null}
            </div>
          </div>
        </fieldset>

        <fieldset className="px-form-section">
          <legend>Main contact</legend>
          <div className="px-form-grid px-form-grid--3">
            <TextField label="Contact person" required value={f.contactName} onChange={set("contactName")} />
            <TextField label="Email" type="email" value={f.primaryEmail} onChange={set("primaryEmail")} />
            <TextField label="Phone" value={f.phone} onChange={set("phone")} />
          </div>
          <div className="px-form-grid px-form-grid--2">
            <TextField label="Industry" value={f.industry} onChange={set("industry")} />
            <TextField label="Country" value={f.country} onChange={set("country")} />
          </div>
        </fieldset>

        <fieldset className="px-form-section">
          <legend>Internal notes</legend>
          <TextField
            label="Notes"
            multiline
            rows={3}
            value={f.notes}
            onChange={set("notes")}
            hint="Staff only. Never shown to the client's portal users."
          />
        </fieldset>
      </FormDialog>

      <MediaPickerModal
        open={logoPickerOpen}
        onClose={() => setLogoPickerOpen(false)}
        title="Select client logo"
        subtitle="Choose from the media library or upload a new file."
        onlyType="image"
        multiple={false}
        allowUpload={true}
        onSelect={(item) => {
          if (!item) return;
          setF((s) => ({ ...s, logoUrl: item.url || item.thumbnailUrl || "", logoMediaId: item._id || "" }));
        }}
      />
    </>
  );
}
